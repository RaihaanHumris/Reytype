const PUNCTUATION_MARKS = [",", ".", ";", "!", "?"];

/**
 * Helper function to get words or quotes based on language, difficulty, and modifiers
 * @param {number} count
 * @param {string} language - 'id' | 'indonesia' | 'en' | 'english'
 * @param {object} options
 */
export const generateWords = (count = 50, language = 'id', options = {}) => {
  const {
    difficulty = 'standard',
    includeNumbers = false,
    includePunctuation = false,
    mode = 'time',
  } = options;

  const isEnglish = language === 'en' || language === 'english';

  // Quote Mode returns the words of a randomly selected quote
  if (mode === 'quote') {
    const quotesList = isEnglish ? englishQuotes : indonesianQuotes;
    const randomQuote = quotesList[Math.floor(Math.random() * quotesList.length)];
    return randomQuote.split(' ');
  }

  let dictionary = isEnglish ? englishWords : indonesianWords;
  if (difficulty === 'kids') {
    dictionary = isEnglish ? kidsEnglishWords : kidsIndonesianWords;
  } else if (difficulty === 'code') {
    dictionary = codingWords;
  }

  if (!dictionary || dictionary.length === 0) return [];

  const selectedWords = [];
  let lastWord = '';

  for (let i = 0; i < count; i++) {
    // Optionally inject a number token ~14% of the time if includeNumbers is active
    if (includeNumbers && Math.random() < 0.14) {
      const numVal = String(Math.floor(Math.random() * 990) + 10);
      selectedWords.push(numVal);
      lastWord = numVal;
      continue;
    }

    let word = dictionary[Math.floor(Math.random() * dictionary.length)];
    // Avoid immediate duplicate words
    if (word === lastWord && dictionary.length > 1) {
      word = dictionary[(Math.floor(Math.random() * (dictionary.length - 1)) + 1) % dictionary.length];
    }
    lastWord = word;

    // Optionally apply capitalization or trailing punctuation if includePunctuation is active
    if (includePunctuation) {
      if (i === 0 || (i > 0 && /[.!?]$/.test(selectedWords[i - 1]))) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }
      if (Math.random() < 0.22) {
        const mark = PUNCTUATION_MARKS[Math.floor(Math.random() * PUNCTUATION_MARKS.length)];
        word = word + mark;
      }
    }

    selectedWords.push(word);
  }

  return selectedWords;
};
